// ========== СОСТОЯНИЕ ИГРЫ (базовые переменные) ==========
int hp = 100;
int resources = 50;       // масло для лампы, стимуляторы
int score = 0;            // "очки выживания" / память
int turn = 1;
int sanity = 100;         // рассудок
int memory = 0;           // восстановленная память (0..100)
vector<int> collectedNotes; // ID собранных записок

// ========== МЕСТО ДЛЯ ФУНКЦИЙ РАЗРАБОТЧИКОВ ==========
