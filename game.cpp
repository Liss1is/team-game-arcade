void finalBattle();

// ========== HUD ==========
void printHUD() {
    cout << "\n\t================ [ХОД: " << turn << " | СЧЕТ: " << score << "] ================\n";
    cout << "\t❤ Здоровье: " << hp << "/100 | ▫ Ресурсы: " << resources << "\n";
    cout << "\t🧠 Рассудок: " << sanity << "/100 | 📜 Память: " << memory << "%\n";
    cout << "\t📖 Записок собрано: " << collectedNotes.size() << "/14\n";
    cout << "\t-------------------------------------------------------------\n";
}

// ========== MAIN ==========
int main() {
    srand(time(NULL));
    int choice = 0;
    initNotes();

    cout << "\t>>> ЗАПУСК: AMNESIA — THE DARK DESCENT<<<\n\n\n";
    cout << "Не забывай... Некоторые вещи нельзя забывать... Тень идёт за мной, нужно торопиться...\nМеня зовут Даниэль... Я живу в Лондоне... в... в... Мэйфэре...\nЧто я натворил? Это безумие. Нельзя забывать, нельзя. Я должен его остановить. Соберись!\nМеня зовут... Я - Даниэль...\n\n";
    cout << "[Вы просыпаетесь в холодном, сыром помещении. Ваше лицо прижато к шершавому, ледяному камню. Вокруг окутывает густая, почти осязаемая тьма.\nВы пытаетесь пошевелиться. Мышцы сводит судорогой, руки дрожат от слабости. Под пальцами — холодные плиты пола. Вы не помните, как здесь оказались. В голове гудит, словно после сильного удара, а мысли разбегаются, как испуганные крысы.\nВы поднимаетесь на ноги, опираясь на холодную каменную стену. Вокруг — кромешная тьма, но ваши глаза постепенно привыкают. Вы видите дневной свет за железными ставнями и след из лепестков вдоль комнаты.\nВолочась по следу дамасской розы, вы приходите в кабинет. След обрывается у маслянной лампы, а возле на столе лежит записка.]\n\n\n";

        cout << "\t[Записка Даниэля самому себе]\n19 августа 1839 г.\n\nЖаль, что я не могу спросить тебя, сколько ты запомнил. Я не знаю, останется ли что-нибудь после того, как я выпью этот напиток.\nДэниэль, не бойся. Знай: забыть — это моё осознанное решение. Пусть этот факт утешит тебя и придаст сил. У всего этого есть цель. Ты — моя последняя попытка всё исправить.\nЕсли будет угодно Богу, то имя Александра Бренненбурга по-прежнему будет вызывать у тебя ожесточение и гнев. Если же нет, то мои слова покажутся тебе ужасными.\nИди в Святая святых, найди Александра и убей его. Он стар и слаб, а ты молод и силён. Ему с тобой не справиться.\n\nИ ещё. За тобой следует тень.\nОна — оживший кошмар, разрушающий реальность.\nЯ испробовал всё, но бороться с ней невозможно. Беги от неё, пока можешь.\nДэниэл, спаси нас обоих. Спустись во тьму, туда, где ждёт Александр, и убей его.\n\nТвоё бывшее «я»,\nДэниэль.\n\n";

        cout << "\tЦель: вспомнить всё и убить Александра\n\n";


    while (hp > 0) {
        printHUD();
        cout << "1. Исследовать тьму (риск / находка записки)\n";
        cout << "2. Отдых и лечение (трата ресурсов)\n";
        cout << "3. Прочитать записку (восстановить память)\n";
        cout << "4. Спуститься в Святая святых (финальная битва)\n";
        cout << "0. Сдаться и зафиксировать счет\n";
        cout << "Выберите действие > ";

        if (!(cin >> choice)) break;

        switch (choice) {
            case 1:
                // [РАЗРАБОТЧИК 2: ПОДКЛЮЧИТ МОДУЛЬ ТЬМЫ (ISSUE #2)]
                exploreDarkness();
                break;
            case 2:
                // [РАЗРАБОТЧИК 2: ПОДКЛЮЧИТ МОДУЛЬ ОТДЫХА (ISSUE #2)]
                restAndHeal();
                break;
            case 3:
                // [РАЗРАБОТЧИК 1: ПОДКЛЮЧИТ ЧТЕНИЕ ЗАПИСОК (ISSUE #1)]
                readNote();
                break;
            case 4:
                // [РАЗРАБОТЧИК 3: ПОДКЛЮЧИТ ФИНАЛЬНУЮ БИТВУ (ISSUE #3)]
                finalBattle();
                break;
            case 0:
                hp = 0;
                break;
            default:
                cout << "\nНет такого действия.\n";
                break;
        }

        // Каждый успешный ход дает очки выживания
        if (hp > 0) {
            turn++;
            score += 10;
        }
    }

    cout << "\n\t=== ИГРА ОКОНЧЕНА. Ваш итоговый рекорд: " << score << " очков! ===\n";
    return 0;
}
// ========== DEV 3: ФИНАЛЬНАЯ БИТВА ==========

void finalBattle() {
    cout << "\n\t>>> СПУСК В СВЯТАЯ СВЯТЫХ <<<\n";
    cout << "Ты входишь в зал с тремя коллонами. Александр ждёт тебя.\n- Я всё сомневался, придёшь ты или нет?\nСкажи, теперь тебе всё ясно и понятно? Я теперь злодей?\nДобро и зло. Такие удобные понятия, но едва применимые в нашем случае.\nНеужели ты так слеп, что не видишь во мне добра?\n";

    if (!hasEnoughMemory()) {
        cout << "\n📜 Восстановлено памяти: " << memory << "%\n";
        cout << "⚠ Даниэль не смог вспомнить всё, ваших сил не хватает.\n";
        cout << "Барон призывает портал.\n- Но ты прости, Даниэль, ты войти не сможешь, на тебе печать тени, вскоре она тебя поглотит.\n";
        cout << "Александр исчезает и комната окутывается в мрак. На стенах появляется красная плоть, стремительно разрастаясь\n";

        cout << "\n💀 Тень поглощает тебя. Даниэль слышит крики убитых невинных людей.\n";
        cout << "\tСобери больше записок (нужно 70% памяти), чтобы дать отпор.\n";
        hp = 0;
        return;
    }

    cout << "\n✔ Ты помнишь всё. Ты помнишь, кто ты. Ты помнишь, что сделал.\n";
    cout << "- Я понимаю, ты сомневаешься в моих намерениях. Но разве я когда либо действительно предавал тебя?\nГлупец, воюя со мной ты погубишь нас обоих.\n";

    // Фаза 1: Бой с Александром
    cout << "\n--- ФАЗА 1: АЛЕКСАНДР ---\n";
    int alexanderHP = 100;
    int round = 0;

    while (alexanderHP > 0 && hp > 0 && round < 5) {
        round++;
        cout << "\nРаунд " << round << " | Твоё HP: " << hp << " | Александр: " << alexanderHP << "\n";
        cout << "1. Атаковать\n2. Использовать стимулятор (10 ресурсов)\n3. Защищаться\n> ";
        int act;
        cin >> act;

        if (act == 1) {
            int dmg = 20 + rand() % 20;
            alexanderHP -= dmg;
            cout << "Ты наносишь " << dmg << " урона!\n";
            // Александр контратакует
            int counter = 10 + rand() % 15;
            hp -= counter;
            if (hp < 0) hp = 0;
            cout << "Александр использует силу сферы: -" << counter << " HP\n";
        } else if (act == 2) {
            if (resources >= 10) {
                resources -= 10;
                hp = min(100, hp + 30);
                cout << "Ты используешь стимулятор. HP: +30\n";
            } else {
                cout << "Недостаточно ресурсов!\n";
            }
        } else if (act == 3) {
            cout << "Ты защищаешься. Урон снижен.\n";
            int counter = 5 + rand() % 10;
            hp -= counter;
            if (hp < 0) hp = 0;
            cout << "Александр атакует: -" << counter << " HP\n";
        }
    }

    if (hp <= 0) {
        cout << "Александр исчезает и комната окутывается в мрак. На стенах появляется красная плоть, стремительно разрастаясь\n";
        cout << "\n💀 Тень поглощает тебя. Даниэль слышит крики убитых невинных людей.\n";
        return;
    }

    cout << "\n✔ Александр повержен! Но Тень всё ещё здесь...\n";

    // Фаза 2: Тень — проверка памяти
    cout << "\n\t--- ФАЗА 2: ТЕНЬ ---\n";
    cout << "Крики замученных тобою людей доносятся отовсюду.\n";

    // Шанс победы зависит от памяти
    int shadowChance = memory; // 0..100
    int roll = rand() % 100;

    cout << "Ты боишься, но не так как раньше.\n";
    cout << "Шанс победы над Тенью: " << shadowChance << "%\n";

    if (roll < shadowChance) {
        cout << "\n✔ Ты вспомнил всё. Тень забирает Александра. Ты свободен.\n";
        cout << "\t🏆 Игра окончена.\n";
        score += 500;
    } else {
        int dmg = 40 + rand() % 30;
        hp -= dmg;
        if (hp < 0) hp = 0;
        cout << "\n💀 Живая плоть окутывает тебя! -" << dmg << " HP\n";
        if (hp <= 0) {
            cout << "\tТень забирает тебя и Александра, вы этого заслужили.\n";
        } else {
            cout << "\tТень забирает Александра. Вы выжили, но какой ценой?\n";
        }
    }
}
