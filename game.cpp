void showMemoryStatus() {
    cout << "\n📜 Восстановлено памяти: " << memory << "%\n";
    if (memory < 40) {
        cout << "⚠ Ты почти ничего не помнишь. В голове туман.\n";
    } else if (memory < 70) {
        cout << "⚠ Ты помнишь фрагменты. Но этого может не хватить.\n";
    } else {
        cout << "✔ Ты помнишь достаточно, чтобы противостоять Александру.\n";
    }
    cout << "Собрано записок: " << collectedNotes.size() << "/14\n";
}

void readNote() {
    // Найти ещё не прочитанные записки
    vector<int> unread;
    for (auto &n : allNotes) {
        if (find(collectedNotes.begin(), collectedNotes.end(), n.id) == collectedNotes.end())
            unread.push_back(n.id);
    }

    if (unread.empty()) {
        cout << "\n📖 Все записки уже прочитаны. Память восстановлена максимально.\n";
        return;
    }

    // Показать доступные (только собранные, но ещё не прочитанные)
    cout << "\n\t=== ДОСТУПНЫЕ ЗАПИСКИ ===\n";
    vector<int> readable;
    for (int id : unread) {
        // В этой реализации считаем, что записка "найдена", если она ещё не прочитана
        // (упрощение: исследование тьмы добавляет записку в collectedNotes при находке)
        readable.push_back(id);
    }

    if (readable.empty()) {
        cout << "Нет новых записок. Исследуй тьму, чтобы найти их.\n";
        return;
    }

    for (int id : readable) {
        auto it = find_if(allNotes.begin(), allNotes.end(),
                          [id](const Note &n){ return n.id == id; });
        if (it != allNotes.end())
            cout << "  [" << it->id << "] " << it->title << "\n";
    }

    cout << "Выберите номер записки (0 — отмена) > ";
    int choice;
    cin >> choice;
    if (choice == 0) return;

    auto it = find_if(allNotes.begin(), allNotes.end(),
                      [choice](const Note &n){ return n.id == choice; });
    if (it == allNotes.end()) {
        cout << "Записка не найдена.\n";
        return;
    }

    // Прочитать
    cout << "\n--- " << it->title << " ---\n" << it->text << "\n";
    memory = min(100, memory + it->memoryBonus);
    score += it->memoryBonus * 2;
    sanity = min(100, sanity + 5); // чтение воспоминаний немного успокаивает
    collectedNotes.push_back(it->id);

    cout << "\n✔ Ты смотришь во тьму. Память восстановлена на +" << it->memoryBonus << "%\n";
    showMemoryStatus();
}

bool hasEnoughMemory() {
    return memory >= 70;
}
